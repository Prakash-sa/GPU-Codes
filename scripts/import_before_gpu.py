"""Copy the "Before GPU Engineering" notebook into docs/before-gpu/ and wire in the navbar.

    git clone --depth 1 https://github.com/BEFORE-GPU-ENGINEERING/BEFORE-GPU-ENGINEERING /tmp/bge
    .venv/bin/python scripts/import_before_gpu.py /tmp/bge

The chapters are copied unchanged (MIT, (c) Ranjan Yadav) except for three edits:
  - each page also loads navbar.css, chapters.js and navbar.js;
  - "index" points at the notebook's own contents page, which becomes before-gpu/index.html;
  - "home" points at this site's home page instead of the author's portfolio.
chapters.js is generated from the upstream toc.html, so re-running after upstream adds
chapters updates the navbar too. navbar.css and navbar.js are ours and are not touched.
"""
import html
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "before-gpu"
UPSTREAM = "https://github.com/BEFORE-GPU-ENGINEERING/BEFORE-GPU-ENGINEERING"


def includes(prefix):
    return (f'<link rel="stylesheet" href="{prefix}navbar.css">\n'
            f'  <script src="{prefix}chapters.js" defer></script>\n'
            f'  <script src="{prefix}navbar.js" defer></script>')


def parse_toc(toc):
    """Phases, parts and chapters in reading order, from the upstream contents page."""
    chapters, phase, part = [], None, None
    token = re.compile(r'class="phase-label">\s*([^<]+?)\s*<'
                       r'|<h2><span[^>]*>(.*?)</span></h2>'
                       r'|<a href="([\w-]+/chapter-(\d+)\.html)"[^>]*>(.*?)</a>', re.S)
    for m in token.finditer(toc):
        if m.group(1):
            phase = m.group(1).strip().title()
        elif m.group(2):
            part = html.unescape(" ".join(m.group(2).split()))
        else:
            title = html.unescape(" ".join(m.group(5).split()))
            title = re.sub(r"^Chapter \d+:\s*", "", title)
            chapters.append({"n": int(m.group(4)), "href": m.group(3), "title": title,
                             "part": part, "phase": phase})
    return chapters


def rewrite(text, replacements):
    for old, new in replacements:
        if old not in text:
            raise SystemExit(f"expected {old!r} not found; upstream layout changed")
        text = text.replace(old, new)
    return text


def main(src):
    src = Path(src)
    toc = (src / "toc.html").read_text(encoding="utf-8")
    chapters = parse_toc(toc)
    if not chapters:
        raise SystemExit("no chapters found in toc.html")

    for d in {Path(c["href"]).parent for c in chapters}:
        shutil.rmtree(OUT / d, ignore_errors=True)
    OUT.mkdir(parents=True, exist_ok=True)
    for name in ("style.css", "script.js", "LICENSE"):
        shutil.copy2(src / name, OUT / name)

    # Contents page: served as before-gpu/index.html; its "home" goes to this site.
    (OUT / "index.html").write_text(rewrite(toc, [
        ('<link rel="stylesheet" href="style.css">',
         '<link rel="stylesheet" href="style.css">\n  ' + includes("")),
        ('href="index.html" class="index-link"', 'href="../index.html" class="index-link"'),
    ]), encoding="utf-8")

    for c in chapters:
        page = (src / c["href"]).read_text(encoding="utf-8")
        page = rewrite(page, [
            ('<link rel="stylesheet" href="../style.css">',
             '<link rel="stylesheet" href="../style.css">\n  ' + includes("../")),
            ('href="../index.html"', 'href="../../index.html"'),   # home: this site, not the portfolio
            ('href="../toc.html"', 'href="../index.html"'),        # index: the contents page
        ])
        dest = OUT / c["href"]
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(page, encoding="utf-8")

    (OUT / "chapters.js").write_text(
        "// Generated by scripts/import_before_gpu.py from the upstream toc.html. Do not edit.\n"
        f"window.BGE = {{upstream: {json.dumps(UPSTREAM)}, chapters: "
        + json.dumps(chapters, indent=1, ensure_ascii=False) + "};\n", encoding="utf-8")
    print(f"{len(chapters)} chapters -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
