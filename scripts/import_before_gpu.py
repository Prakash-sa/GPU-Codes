"""Import the "Before GPU Engineering" notebook as pages under notes/before-gpu/.

    git clone --depth 1 https://github.com/BEFORE-GPU-ENGINEERING/BEFORE-GPU-ENGINEERING /tmp/bge
    .venv/bin/python scripts/import_before_gpu.py /tmp/bge

The upstream chapters (MIT, (c) Ranjan Yadav) are standalone HTML pages. Each one becomes a
Markdown page that keeps the chapter's HTML as-is (text, highlights, SVG diagrams), so it
renders inside the site theme like every other page:
  - top-level <h2> section titles become Markdown headings, so the page TOC and search work;
  - everything else stays in raw <div class="bge"> blocks, styled by docs/stylesheets/extra.css;
  - the notebook chrome (date header, title row, prev/next sidebar) is dropped: the date and
    part go into a line under the title, and the theme provides navigation.
It also writes notes/before-gpu/index.md (the contents page), redirect stubs at the old
before-gpu/*.html URLs, and the nav block in mkdocs.yml between the before-gpu markers.
"""
import html
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "notes" / "before-gpu"
OLD = ROOT / "docs" / "before-gpu"          # where the first copy was published; now redirects
MKDOCS = ROOT / "mkdocs.yml"
UPSTREAM = "https://github.com/BEFORE-GPU-ENGINEERING/BEFORE-GPU-ENGINEERING"
NAV_START = "      # before-gpu nav: generated by scripts/import_before_gpu.py\n"
NAV_END = "      # end before-gpu nav\n"
CREDIT = (f'From [Before GPU Engineering]({UPSTREAM}) by Ranjan Yadav, '
          f'used under the [MIT license](LICENSE.txt).')


def parse_toc(toc):
    """Phases, parts and chapters in reading order, from the upstream contents page."""
    chapters, phase, part = [], None, None
    token = re.compile(r'class="phase-label">\s*([^<]+?)\s*<'
                       r'|<h2><span[^>]*>(.*?)</span></h2>'
                       r'|<a href="([\w-]+)/chapter-(\d+)\.html"[^>]*>(.*?)</a>', re.S)
    for m in token.finditer(toc):
        if m.group(1):
            phase = m.group(1).strip().title()
        elif m.group(2):
            part = html.unescape(" ".join(m.group(2).split()))
        else:
            title = html.unescape(" ".join(m.group(5).split()))
            title = re.sub(r"^Chapter \d+:\s*", "", title)
            chapters.append({"n": int(m.group(4)), "dir": m.group(3), "title": title,
                             "part": part, "phase": phase})
    return chapters


def inner_div(page, cls):
    """Inner HTML of the first <div class="cls">, matching nested divs."""
    start = page.index(f'<div class="{cls}">') + len(f'<div class="{cls}">')
    depth = 1
    for m in re.compile(r"<div\b|</div>").finditer(page, start):
        depth += 1 if m.group() != "</div>" else -1
        if depth == 0:
            return page[start:m.start()]
    raise ValueError(f"unclosed div.{cls}")


def fix_links(body):
    """Chapter links: upstream chapter-N.html files -> this site's directory URLs."""
    body = re.sub(r'href="\.\./([\w-]+)/chapter-(\d+)\.html', r'href="../../\1/chapter-\2/', body)
    return re.sub(r'href="chapter-(\d+)\.html', r'href="../chapter-\1/', body)


def md_escape(text):
    return re.sub(r"([\\`*_$\[\]])", r"\\\1", text)


def to_markdown(body, meta):
    """Raw HTML blocks, split at top-level single-line <h2>s, which become Markdown headings."""
    lines = body.strip("\n").splitlines()
    indent = min((len(l) - len(l.lstrip()) for l in lines if l.strip()), default=0)
    lines = [l[indent:] for l in lines]
    h2 = re.compile(r'^<h2><span class="([\w-]+)">(.*?)</span></h2>$')
    out, chunk, depth = [], [], 0

    def flush():
        text = "\n".join(chunk).strip("\n")
        if text.strip():
            out.append(f'<div class="bge">\n{text}\n</div>')
        chunk.clear()

    for line in lines:
        m = h2.match(line.strip())
        if depth == 0 and m and "<" not in m.group(2):
            flush()
            title = md_escape(html.unescape(m.group(2)))
            out.append(f'## <span class="{m.group(1)}">{title}</span>')
        else:
            chunk.append(line)
            if line.strip().startswith("</h1>") or line.rstrip().endswith("</h1>"):
                chunk.append(meta)
        depth += len(re.findall(r"<div\b", line)) - len(re.findall(r"</div>", line))
    flush()
    return "\n\n".join(out)


def nav_block(chapters):
    lines = ["      - Before GPU Engineering:",
             "          - Overview: notes/before-gpu/index.md"]
    phase = part = None
    for c in chapters:
        if c["phase"] != phase:
            phase = c["phase"]
            lines.append(f"          - {phase}:")
        if c["part"] != part:
            part = c["part"]
            lines.append(f"              - {json.dumps(part)}:")
        label = json.dumps(f"{c['n']}. {c['title']}", ensure_ascii=False)
        lines.append(f"                  - {label}: notes/before-gpu/{c['dir']}/chapter-{c['n']}.md")
    return "\n".join(lines) + "\n"


def contents_page(chapters):
    out = ["# Before GPU Engineering", "",
           "*A first-principles climb from the absolute bottom of hardware to the top of GPU "
           "architecture.* A 56-chapter notebook by Ranjan Yadav: transistors, memory buses and "
           "warps first, then CUDA's execution model, the memory wall, and profiling. Read it "
           "before (or next to) the [GPU programming notes](../index.md); the chapters build on "
           "each other, so start at Chapter 1 and read in order.", "",
           '<div id="bge-continue"></div>', "",
           f"!!! note \"Source and license\"\n    {CREDIT} The upstream repository is still adding "
           "chapters (Phase 5 is in progress); `scripts/import_before_gpu.py` pulls new ones in.", ""]
    phase = part = None
    for c in chapters:
        if c["phase"] != phase:
            phase = c["phase"]
            out += [f"## {phase}", ""]
        if c["part"] != part:
            if part is not None and out[-1] != "":
                out.append("")
            part = c["part"]
            out += [f"### {part}", ""]
        out.append(f"- [Chapter {c['n']}: {md_escape(c['title'])}]({c['dir']}/chapter-{c['n']}.md)")
    return "\n".join(out) + "\n"


def redirect(to):
    return (f'<!DOCTYPE html>\n<html lang="en"><head><meta charset="utf-8">\n'
            f'<title>Moved</title><link rel="canonical" href="{to}">\n'
            f'<meta http-equiv="refresh" content="0; url={to}">\n</head>\n'
            f'<body><p>Moved to <a href="{to}">{to}</a>.</p></body></html>\n')


def main(src):
    src = Path(src)
    chapters = parse_toc((src / "toc.html").read_text(encoding="utf-8"))
    if not chapters:
        raise SystemExit("no chapters found in toc.html")

    shutil.rmtree(OUT, ignore_errors=True)
    shutil.rmtree(OLD, ignore_errors=True)
    OUT.mkdir(parents=True)
    shutil.copy2(src / "LICENSE", OUT / "LICENSE.txt")
    (OUT / "index.md").write_text(contents_page(chapters), encoding="utf-8")
    OLD.mkdir()
    (OLD / "index.html").write_text(redirect("../notes/before-gpu/"), encoding="utf-8")

    for i, c in enumerate(chapters):
        page = (src / c["dir"] / f"chapter-{c['n']}.html").read_text(encoding="utf-8")
        date = re.search(r'class="date-value">([^<]*)<', page)
        meta = (f'<p class="bge-meta">{c["phase"]} · {html.escape(c["part"])} · '
                f'Chapter {c["n"]} of {len(chapters)}'
                + (f' · notebook date {date.group(1).strip()}' if date else "") + "</p>")
        body = to_markdown(fix_links(inner_div(page, "notebook-grid-content")), meta)
        title = json.dumps(f"{c['n']}. {c['title']}", ensure_ascii=False)
        credit = CREDIT.replace("(LICENSE.txt)", "(../LICENSE.txt)")
        md = (f"---\ntitle: {title}\n---\n\n"
              f"{body}\n\n---\n\n<small>{credit}</small>\n")
        dest = OUT / c["dir"] / f"chapter-{c['n']}.md"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(md, encoding="utf-8")
        old = OLD / c["dir"] / f"chapter-{c['n']}.html"
        old.parent.mkdir(parents=True, exist_ok=True)
        old.write_text(redirect(f"../../notes/before-gpu/{c['dir']}/chapter-{c['n']}/"), encoding="utf-8")

    cfg = MKDOCS.read_text(encoding="utf-8")
    if NAV_START not in cfg or NAV_END not in cfg:
        raise SystemExit("mkdocs.yml: before-gpu nav markers not found")
    head, rest = cfg.split(NAV_START)
    MKDOCS.write_text(head + NAV_START + nav_block(chapters) + NAV_END + rest.split(NAV_END)[1],
                      encoding="utf-8")
    print(f"{len(chapters)} chapters -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
